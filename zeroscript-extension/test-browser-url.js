// Regression test for URL validation in background.js (run with: node test-browser-url.js)
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync(require("node:path").join(__dirname, "background.js"), "utf8");
const main = fs.readFileSync(require("node:path").join(__dirname, "core/main.js"), "utf8");
const helpers = source.match(/function requestedBrowserUrl\(value\) \{[\s\S]*?\n\}\nfunction isAllowedBrowserUrl\(value\) \{[\s\S]*?\n\}/);
assert.ok(helpers, "URL helper functions should exist in background.js");
const context = { URL };
vm.runInNewContext(helpers[0], context);
assert.equal(context.isAllowedBrowserUrl("https://www.youtube.com"), true);
assert.equal(context.isAllowedBrowserUrl("http://www.youtube.com"), true);
assert.equal(context.isAllowedBrowserUrl("  https://www.youtube.com/watch?v=abc  "), true);
assert.equal(context.isAllowedBrowserUrl({ url: "https://www.youtube.com" }), true);
assert.equal(context.isAllowedBrowserUrl("www.youtube.com"), true);
assert.equal(context.isAllowedBrowserUrl("file:///etc/passwd"), false);
assert.equal(context.isAllowedBrowserUrl("javascript:alert(1)"), false);
assert.equal(context.isAllowedBrowserUrl("https://"), false);
const normalizer = source.match(/function normalizeBrowserArgs\(value, senderTabId\) \{[\s\S]*?\n\}/);
assert.ok(normalizer, "browser argument aliases should be normalized before review and dispatch");
const normalizerContext = {};
vm.runInNewContext(normalizer[0], normalizerContext);
assert.deepEqual(JSON.parse(JSON.stringify(normalizerContext.normalizeBrowserArgs({ elementId: "zs-12", tabId: 238067010, text: "Império" }, 99))), { tabId: 238067010, text: "Império", id: "zs-12" });
assert.deepEqual(JSON.parse(JSON.stringify(normalizerContext.normalizeBrowserArgs({ element_id: "zs-13", tab: 17 }, 99))), { id: "zs-13", tabId: 17 });
assert.deepEqual(JSON.parse(JSON.stringify(normalizerContext.normalizeBrowserArgs({ node_id: "zs-14" }, 99))), { id: "zs-14", tabId: 99 });
assert.match(source, /const BRIDGE_WS_URL =/);
assert.match(source, /if \(ws !== socket\) return; \/\/ stale close from an older connection/);
assert.match(source, /bridge socket closed/);
assert.doesNotMatch(source, /^const URL\s*=/m, "bridge socket constant must not shadow global URL");
assert.match(source, /name: "agent\.browser\.snapshot"[^\n]*active: \{ type: "boolean"/);
assert.match(source, /function targetTabId\(args, sender\)/);
assert.match(source, /function activateBrowserTab\(tabId\)/);
assert.match(source, /await restoreAgentTab\(sender, tabId, args\.active !== false\)/);
assert.match(source, /async function browserActionNeedsApproval\(/);
assert.match(source, /\(tabProfile \|\| agentProfile\) !== "broad"/);
assert.match(source, /const browserArgs = normalizeBrowserArgs\(msg\.arguments, sender\?\.tab\?\.id\)/);
const normalizeAt = source.indexOf("const browserArgs = normalizeBrowserArgs(msg.arguments, sender?.tab?.id)");
const approvalAt = source.indexOf("browserActionNeedsApproval(msg.name, browserArgs, sender)");
const dispatchAt = source.indexOf("extensionBrowserCall(msg.name, browserArgs, sender)");
assert.ok(normalizeAt >= 0 && normalizeAt < approvalAt && approvalAt < dispatchAt, "normalize element IDs before approval and execution");
const dom = fs.readFileSync(require("node:path").join(__dirname, "core/dom_snapshot.js"), "utf8");
assert.match(dom, /function classify\(action, id, details = \{\}\)/);
assert.match(dom, /sensitive or external-effect control/);
assert.match(dom, /function rootsFor\(deep = false\)/);
assert.match(dom, /role='listitem'/);
assert.match(dom, /pageText\(deep\)/);
assert.match(dom, /inspectedRoots: roots\.length/);
assert.match(dom, /candidateCount: candidates\.length/);
assert.match(dom, /for \(const root of roots\) observeRoot\(root\)/);
assert.match(dom, /async function waitFor\(/);
assert.match(dom, /async function scroll\(/);
assert.match(dom, /function pressKey\(/);
assert.match(dom, /function clickAt\(/);
assert.match(dom, /coordinateSpace === "image"/);
assert.match(dom, /Synthetic DOM keyboard events are not trusted OS keystrokes/);
assert.match(source, /name: "agent\.browser\.press_key"/);
assert.match(source, /name: "agent\.browser\.wait"/);
assert.match(source, /name: "agent\.browser\.scroll"/);
assert.match(source, /name: "agent\.browser\.screenshot"/);
assert.match(source, /name: "agent\.browser\.click_at"/);
assert.match(source, /chrome\.tabs\.captureVisibleTab/);
assert.match(main, /t\.name !== "agent\.browser\.screenshot" \|\| P\.supportsVision/);
assert.match(main, /if \(r\.ok && name\.startsWith\("agent\."\)\) \{[\s\S]*?if \(r\.images && r\.images\.length\)/);
assert.match(main, /A\.pendingImages = r\.images/);
console.log("browser URL, dynamic snapshots, keyboard, waits, virtualized scroll and vision fallback checks passed");
