// Static regression checks for the extension approval flow (node test-approval-ui.js)
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const dir = __dirname;
const read = (name) => fs.readFileSync(path.join(dir, name), "utf8");
const manifest = JSON.parse(read("manifest.json"));
const background = read("background.js");
const popup = read("popup.html") + read("popup.js");
const overlay = read("core/approval-overlay.js");
assert.ok(manifest.permissions.includes("notifications"));
assert.match(background, /chrome\.notifications\.create\("zs-approval"/);
assert.match(background, /function announceAgentApproval\(approval\)[\s\S]*?chrome\.tabs\.sendMessage\(approval\.sourceTabId, \{ type: "zs-approval-request", approval \}/);
assert.doesNotMatch(background, /tabs\.create\(\{\s*url: chrome\.runtime\.getURL\("approval\.html"\)/);
assert.match(background, /case "reject_agent"/);
assert.match(background, /const rejected = agentApproval;\s*agentApproval = null;/);
assert.match(background, /approved: true/);
assert.match(background, /const approval = agentApproval;\s*agentApproval = null;/);
assert.match(background, /sendResponse\(\{ \.\.\.r, approvalConsumed: true \}\)/);
assert.match(background, /function answerOnce\(state, result\)/);
assert.match(background, /if \(r\?\.result\?\.status !== "approval_required"\) answerOnce\(responseState, r\)/);
assert.match(background, /answerOnce\(approval\.responseState, r\)/);
assert.match(background, /answerOnce\(rejected\.responseState/);
assert.match(background, /approval request expired without a decision/);
assert.match(popup, /id="approve"/);
assert.match(popup, /id="reject"/);
assert.match(popup, /JSON\.stringify\(redact\(pending\.args \|\| \{\}\), null, 2\)/);
assert.match(overlay, /ROOT_ID = "zs-approval-modal"/);
assert.match(overlay, /Aprovação necessária/);
assert.match(overlay, /Aprovar e executar/);
assert.match(overlay, /Rejeitar/);
assert.match(overlay, /result\?\.approvalConsumed/);
assert.match(overlay, /Não clique novamente/);
assert.match(overlay, /textContent = JSON\.stringify\(redact\(request\.args \|\| \{\}\), null, 2\)/);
assert.match(popup, /button\.disabled = otherButton\.disabled = true/);
assert.ok(manifest.content_scripts.some((entry) => (entry.js || []).includes("core/approval-overlay.js")));
console.log("in-page approval modal regression checks passed");
